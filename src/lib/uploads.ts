import { randomBytes } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import { config } from "@/lib/config";

export const MAX_UPLOAD_BYTES = 5 * 1024 * 1024;

const EXTENSIONS: Record<string, string> = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
  "application/pdf": "pdf",
};

export const IMAGE_TYPES = ["image/jpeg", "image/png", "image/webp"];
export const DOCUMENT_TYPES = [...IMAGE_TYPES, "application/pdf"];

export const DOCUMENT_KINDS = ["Aadhaar card", "PAN card", "Trade licence", "Training certificate", "Other"];

export type UploadFolder = "bookings" | "documents";

export function uploadedFile(value: FormDataEntryValue | null) {
  return value instanceof File && value.size > 0 ? value : null;
}

export function validateUpload(file: File, allowedTypes: string[]) {
  if (!allowedTypes.includes(file.type)) {
    return `Only ${allowedTypes.map((t) => EXTENSIONS[t]).join(", ")} files are allowed.`;
  }
  if (file.size > MAX_UPLOAD_BYTES) return "Files must be 5 MB or smaller.";
  return null;
}

// Stores the file under UPLOAD_DIR with a random name and returns its storage key.
export async function saveUpload(file: File, folder: UploadFolder) {
  const key = `${folder}/${randomBytes(16).toString("hex")}.${EXTENSIONS[file.type]}`;
  const target = resolveKey(key);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, Buffer.from(await file.arrayBuffer()));
  return key;
}

export async function readUpload(key: string) {
  return readFile(resolveKey(key));
}

export function contentTypeFor(key: string) {
  const ext = key.split(".").pop();
  return Object.entries(EXTENSIONS).find(([, e]) => e === ext)?.[0] ?? "application/octet-stream";
}

// Keys are generated by saveUpload; reject anything else so paths can't escape the folder.
export function isUploadKey(key: string) {
  return /^(bookings|documents)\/[a-f0-9]{32}\.(jpg|png|webp|pdf)$/.test(key);
}

function resolveKey(key: string) {
  if (!isUploadKey(key)) throw new Error("Invalid upload key");
  return path.resolve(config.uploadDir, key);
}

export function fileUrl(key: string) {
  return `/api/files/${key}`;
}
